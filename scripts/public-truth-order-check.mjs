import fs from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const signalsPath = path.join(ROOT, "src", "data", "studioSignals.ts");
const contractPath = path.join(ROOT, "docs", "PUBLIC_TRUTH_ORDER.md");
const failures = [];

if (!fs.existsSync(signalsPath)) {
  failures.push("missing src/data/studioSignals.ts");
}
if (!fs.existsSync(contractPath)) {
  failures.push("missing docs/PUBLIC_TRUTH_ORDER.md");
}

const signalsSource = fs.existsSync(signalsPath)
  ? fs.readFileSync(signalsPath, "utf8")
  : "";
const contract = fs.existsSync(contractPath)
  ? fs.readFileSync(contractPath, "utf8")
  : "";

function escapeRegExp(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function findMatchingDelimiter(source, openIndex, openChar, closeChar) {
  let depth = 0;
  let quote = "";
  let escaped = false;
  let lineComment = false;
  let blockComment = false;

  for (let index = openIndex; index < source.length; index += 1) {
    const char = source[index];
    const next = source[index + 1];

    if (lineComment) {
      if (char === "\n") lineComment = false;
      continue;
    }
    if (blockComment) {
      if (char === "*" && next === "/") {
        blockComment = false;
        index += 1;
      }
      continue;
    }
    if (quote) {
      if (escaped) {
        escaped = false;
        continue;
      }
      if (char === "\\") {
        escaped = true;
        continue;
      }
      if (char === quote) quote = "";
      continue;
    }

    if (char === "/" && next === "/") {
      lineComment = true;
      index += 1;
      continue;
    }
    if (char === "/" && next === "*") {
      blockComment = true;
      index += 1;
      continue;
    }
    if (char === '"' || char === "'" || char === "`") {
      quote = char;
      continue;
    }
    if (char === openChar) {
      depth += 1;
      continue;
    }
    if (char === closeChar) {
      depth -= 1;
      if (depth === 0) return index;
    }
  }

  return -1;
}

function extractSignalsBlock(source) {
  const declaration = /export\s+const\s+STUDIO_SIGNALS\s*:\s*StudioSignal\s*\[\s*\]\s*=\s*\[/m.exec(
    source,
  );
  if (!declaration) return "";
  const openIndex = declaration.index + declaration[0].lastIndexOf("[");
  const closeIndex = findMatchingDelimiter(source, openIndex, "[", "]");
  return closeIndex < 0 ? "" : source.slice(openIndex + 1, closeIndex);
}

function extractSignalObject(block, id) {
  const idPattern = new RegExp(
    `\\bid\\s*:\\s*(["'])${escapeRegExp(id)}\\1`,
  );
  const idMatch = idPattern.exec(block);
  if (!idMatch) return "";

  for (
    let objectStart = block.lastIndexOf("{", idMatch.index);
    objectStart >= 0;
    objectStart = block.lastIndexOf("{", objectStart - 1)
  ) {
    const objectEnd = findMatchingDelimiter(block, objectStart, "{", "}");
    if (objectEnd >= idMatch.index) {
      return block.slice(objectStart, objectEnd + 1);
    }
  }

  return "";
}

const parserProbe = `
export const STUDIO_SIGNALS : StudioSignal[] =
  [
    {
      id : 'probe-signal',
      summary: "delimiter text { stays inside strings }",
      action: { kind: "section", target: "proof" },
    },
    {
      id: "other-signal",
      summary: "safe",
    },
  ];
`;
const parserProbeBlock = extractSignalsBlock(parserProbe);
const parserProbeObject = extractSignalObject(parserProbeBlock, "probe-signal");
if (!parserProbeBlock || !parserProbeObject.includes("probe-signal")) {
  failures.push(
    "truth-order parser self-test failed for indented arrays or nested signal objects",
  );
}

const signalsBlock = extractSignalsBlock(signalsSource);
if (!signalsBlock) {
  failures.push("src/data/studioSignals.ts: live STUDIO_SIGNALS array could not be isolated");
}

const engineSignal = extractSignalObject(
  signalsBlock,
  "box-o-battles-math-spine-v0-1",
);
const cardSignal = extractSignalObject(signalsBlock, "box-o-battles-owner-card");

for (const required of [
  "The Arbiter no longer guesses",
  "BOB #003 has not been recomputed through this engine",
]) {
  if (!engineSignal.includes(required)) {
    failures.push(`tested-engine signal lost required truth: ${required}`);
  }
}

for (const required of [
  "BOB #003 remains an owner-held immutable card",
  "The packet predates the merged Math Spine core",
]) {
  if (!cardSignal.includes(required)) {
    failures.push(`immutable-card signal lost required truth: ${required}`);
  }
}

for (const required of [
  "inspect repository truth and current main",
  "inspect the owner code that creates the output",
  "A polished card is not proof of a working evaluator",
  "BOB #003 has not yet been recomputed through the new engine",
]) {
  if (!contract.includes(required)) {
    failures.push(`public truth contract lost required law: ${required}`);
  }
}

for (const forbidden of [
  "BOB #003 was recomputed",
  "BOB #003 generated by the current Math Spine",
  "statistically calibrated",
]) {
  if (signalsBlock.includes(forbidden)) {
    failures.push(`unsupported live signal claim returned: ${forbidden}`);
  }
}

if (failures.length > 0) {
  console.error(
    "Public truth order check failed:\n" +
      failures.map((failure) => `- ${failure}`).join("\n"),
  );
  process.exit(1);
}

console.log(
  "Public truth order passed: delimiter-aware live signal extraction keeps tested-engine and immutable-card objects distinct from comments and dead text.",
);
